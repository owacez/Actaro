// Converts MuscleMap's body outline data (Swift sources, MIT) into a TypeScript module.
// Usage: node scripts/musclemap-paths.mjs <path-to-MuscleMap-clone>
// Source: https://github.com/melihcolpan/MuscleMap (MIT, © 2026 Melih Colpan).
// Only the 18 main muscle regions and the inert silhouette parts are kept; MuscleMap's
// optional sub-group regions overlap them and are not used here.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('Pass the path to a MuscleMap clone.');
const data = join(root, 'Sources', 'MuscleMap', 'Data');
const revision = process.argv[3] ?? 'unknown';

const muscles = [
  'trapezius',
  'deltoids',
  'chest',
  'upper-back',
  'serratus',
  'biceps',
  'triceps',
  'forearm',
  'abs',
  'obliques',
  'lower-back',
  'gluteal',
  'quadriceps',
  'hamstring',
  'adductors',
  'hip-flexors',
  'calves',
  'tibialis',
];
const silhouette = ['head', 'hair', 'neck', 'hands', 'feet', 'knees', 'ankles'];
const kebab = (name) => name.replace(/[A-Z]/g, (letter) => '-' + letter.toLowerCase());

function parse(file) {
  const text = readFileSync(join(data, file), 'utf8');
  const parts = {};
  for (const chunk of text.split('BodyPartPathData(').slice(1)) {
    const slug = kebab(/slug:\s*\.(\w+)/.exec(chunk)?.[1] ?? '');
    if (!muscles.includes(slug) && !silhouette.includes(slug)) continue;
    const paths = [...chunk.matchAll(/"([^"]+)"/g)].map((match) => match[1]);
    if (!paths.length) continue;
    (parts[slug] ??= []).push(...paths);
  }
  return parts;
}

const body = {
  male: {
    front: { viewBox: '0 95 727 1280', parts: parse('MaleFrontPaths.swift') },
    back: { viewBox: '718 95 727 1280', parts: parse('MaleBackPaths.swift') },
  },
  female: {
    front: { viewBox: '0 0 650 1450', parts: parse('FemaleFrontPaths.swift') },
    back: { viewBox: '823 0 650 1450', parts: parse('FemaleBackPaths.swift') },
  },
};

const header = `// Generated by scripts/musclemap-paths.mjs. Do not edit by hand.
// Body outlines from MuscleMap by Melih Colpan (https://github.com/melihcolpan/MuscleMap),
// revision ${revision}.
//
// MIT License. Copyright (c) 2026 Melih Colpan.
// Permission is hereby granted, free of charge, to any person obtaining a copy of this
// software and associated documentation files (the "Software"), to deal in the Software
// without restriction, including without limitation the rights to use, copy, modify,
// merge, publish, distribute, sublicense, and/or sell copies of the Software, and to
// permit persons to whom the Software is furnished to do so, subject to the following
// conditions: The above copyright notice and this permission notice shall be included in
// all copies or substantial portions of the Software. THE SOFTWARE IS PROVIDED "AS IS",
// WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED.
`;
const out = `${header}
export type BodyFigure = 'male' | 'female';
export type BodySide = 'front' | 'back';
export const bodyPaths: Record<
  BodyFigure,
  Record<BodySide, { viewBox: string; parts: Record<string, readonly string[]> }>
> = ${JSON.stringify(body)};
`;
writeFileSync(join('src', 'features', 'muscles', 'body-paths.ts'), out);
const count = Object.values(body).flatMap((figure) =>
  Object.values(figure).map((side) => Object.keys(side.parts).length),
);
console.log('regions per figure/side:', count.join(', '));
